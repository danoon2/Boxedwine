package boxedwine.org.writers;

import boxedwine.org.data.VkData;
import boxedwine.org.data.VkFunction;
import boxedwine.org.data.VkParam;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

public class VkC {
    // Leaf assembly keeps ESP at the i386 ABI entry frame. The immediate after
    // int 9a identifies the command; arguments (including inline uint64_t) stay
    // on the original stack. EDX:EAX already carries 64-bit integer returns.
    private static void thunk(StringBuilder out, String name, String index, boolean hidden) {
        out.append("__asm__(\".text\\n.globl " + name + "\\n");
        if (hidden) out.append(".hidden " + name + "\\n");
        out.append(".type " + name + ",@function\\n" + name + ":\\n");
        out.append("int $0x9a\\n.long " + index + "\\nret\\n");
        out.append(".size " + name + ",.-" + name + "\\n\");\n\n");
    }

    public static void write(VkData data, String dir) throws Exception {
        StringBuilder out = new StringBuilder();
        out.append("// DON'T MODIFY, this is autogenerated\n");
        out.append("#include <dlfcn.h>\n#include <stdint.h>\n");
        out.append("#define U32 uint32_t\n#define U64 uint64_t\n\n");
        for (VkFunction fn : data.functions) {
            boolean device = fn.name.equals("vkGetDeviceProcAddr");
            boolean instance = fn.name.equals("vkGetInstanceProcAddr");
            if (device || instance) {
                String helper = device ? "boxedwineHasDeviceProc" : "boxedwineHasInstanceProc";
                out.append("extern U32 " + helper + "(U32 handle, U32 name);\n");
                thunk(out, helper, fn.def, true);
                out.append("U32 " + fn.name + "(U32 handle, U32 name) {\n");
                out.append("    if (!name || !" + helper + "(handle, name)) return 0;\n");
                out.append("    return (U32)dlsym(RTLD_DEFAULT, (const char*)name);\n}\n\n");
            } else {
                int returnSize = fn.returnType.sizeof;
                if (returnSize != 0 && returnSize != 4 && returnSize != 8)
                    throw new Exception("Unhandled return size: " + fn.name);
                for (VkParam param : fn.params) {
                    if (param.getStackWords() != 1 && param.getStackWords() != 2)
                        throw new Exception("Unhandled argument size: " + fn.name + "." + param.name);
                }
                thunk(out, fn.name, fn.def, false);
            }
        }
        Files.writeString(Path.of(dir, "vk.c"), out.toString().stripTrailing() + "\n", StandardCharsets.UTF_8);
    }
}
