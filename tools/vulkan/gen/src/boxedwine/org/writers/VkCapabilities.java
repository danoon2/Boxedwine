package boxedwine.org.writers;

import boxedwine.org.data.*;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.Set;

public class VkCapabilities {
    private static boolean unsupportedType(VkData data, VkType type, Set<VkType> visited) {
        if (!visited.add(type)) return false;
        if (data.stubMarshalRead.contains(type.name) ||
                (type.needMarshalOut && data.stubMarshalWrite.contains(type.name))) return true;
        for (VkParam member : type.members) {
            if (unsupportedType(data, member.paramType, visited)) return true;
        }
        return false;
    }

    public static void write(VkData data, String dir) throws Exception {
        StringBuilder out = new StringBuilder("// DON'T MODIFY, this is autogenerated\n");
        Set<String> unsupportedCommands = new java.util.TreeSet<>(data.unimplementedFunctions);
        for (VkExtension extension : data.extensions) {
            boolean supported = !extension.removed && extension.specVersion != null;
            for (VkExtension.VkExtensionRequire require : extension.require) {
                if (require.api != null && !java.util.Arrays.asList(require.api.split(",")).contains("vulkan")) continue;
                for (VkFunction fn : require.functions) {
                    if (data.getFunctionByName(fn.name) == null || data.unimplementedFunctions.contains(fn.name)) supported = false;
                }
                for (VkType type : require.types) {
                    if (unsupportedType(data, type, new HashSet<>())) supported = false;
                }
            }
            // Guest callbacks are not yet delivered; logging on the host is not
            // sufficient to expose the debug callback extensions to applications.
            if (extension.name.equals("VK_EXT_debug_report") || extension.name.equals("VK_EXT_debug_utils") ||
                    extension.name.equals("VK_EXT_host_image_copy") || extension.name.equals("VK_EXT_map_memory_placed")) {
                supported = false;
                if (extension.name.startsWith("VK_EXT_debug_"))
                    for (VkExtension.VkExtensionRequire require : extension.require)
                        for (VkFunction fn : require.functions) unsupportedCommands.add(fn.name);
            }
            if (supported) {
                out.append("VK_" + (extension.type.equals("instance") ? "INSTANCE" : "DEVICE")
                        + "_EXTENSION(\"" + extension.name + "\", " + extension.specVersion + ", \""
                        + (extension.depends == null ? "" : extension.depends) + "\")\n");
            }
        }
        for (VkFunction fn : data.functions) {
            for (VkParam param : fn.params)
                if (unsupportedType(data, param.paramType, new HashSet<>())) unsupportedCommands.add(fn.name);
        }
        out.append("#ifdef VK_UNSUPPORTED_COMMAND\n");
        for (String command : unsupportedCommands) out.append("VK_UNSUPPORTED_COMMAND(\"" + command + "\")\n");
        out.append("#endif\n");
        Files.writeString(Path.of(dir, "vkextensions.h"), out);
    }
}
