#!/usr/bin/env python3
"""Regenerate the embedded UDF 1.02 fixture with genisoimage (Linux).

No runtime test dependency on genisoimage or host fixture paths is needed.
The tests mutate allocation descriptors to cover inline, fragmented and sparse
files; their ordinary filesystem comes from this independent image writer.
"""
from pathlib import Path
import argparse
import struct
import subprocess
import tempfile
import zlib


def write_session_fixture(files, image):
    session_start = 450
    subprocess.run(["genisoimage", "-quiet", "-udf", "-J", "-V", "BOXEDWINE_UDF",
                    "-C", f"0,{session_start}", "-o", str(image), str(files)], check=True)
    data = image.read_bytes()
    packed = zlib.compress(data, 9)
    target = Path(__file__).resolve().parents[2] / "source/test/fs/testUdfSessionFixture.h"
    text = "// Generated by tools/input/generate_udf_fixture.py; do not edit.\n"
    text += "// Copyright (C) 2026 The BoxedWine Team; SPDX-License-Identifier: GPL-2.0-or-later\n"
    text += f"constexpr U32 UDF_SESSION_FIXTURE_SIZE = {len(data)};\n"
    text += f"constexpr U32 UDF_SESSION_FIXTURE_START = {session_start};\n"
    text += "static const U8 udfSessionFixtureCompressed[] = {\n"
    for start in range(0, len(packed), 20):
        text += "    " + ", ".join(f"0x{byte:02x}" for byte in packed[start:start + 20]) + ",\n"
    target.write_text(text + "};\n")
    print(f"Wrote {target}: {len(data)} bytes, {len(packed)} compressed")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--session-only", action="store_true", help="regenerate only the nonzero-session fixture")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / "source/test/fs/testUdfFixture.h"
    with tempfile.TemporaryDirectory() as temporary:
        root = Path(temporary)
        files = root / "files"
        (files / "DIR").mkdir(parents=True)
        (files / "FILE.TXT").write_bytes(b"A" * 2048 + b"B" * 2048 + b"C")
        (files / "EMPTY").touch()
        (files / "DIR/caf\u00e9.txt").write_bytes(b"HELLO")
        image = root / "fixture.iso"
        write_session_fixture(files, root / "session.iso")
        if args.session_only:
            return
        subprocess.run(["genisoimage", "-quiet", "-udf", "-J", "-V", "BOXEDWINE_UDF",
                        "-o", str(image), str(files)], check=True)
        data = image.read_bytes()

    def u32(offset):
        return struct.unpack_from("<I", data, offset)[0]

    partition = next(u32(lba * 2048 + 188) for lba in range(32, 64)
                     if data[lba * 2048:lba * 2048 + 2] == b"\x05\0")
    fsd = next(lba for lba in range(partition, partition + 32)
               if data[lba * 2048:lba * 2048 + 2] == b"\0\x01")
    root_entry = partition + u32(fsd * 2048 + 404)
    directory = partition + u32(root_entry * 2048 + 180)
    entries = {}
    offset = directory * 2048
    end = offset + u32(root_entry * 2048 + 56)
    while offset < end:
        length = data[offset + 19]
        extra = struct.unpack_from("<H", data, offset + 36)[0]
        name = data[offset + 38 + extra:offset + 38 + extra + length]
        if name and name[0] == 8:
            entries[name[1:].decode("latin1")] = partition + u32(offset + 24)
        offset += (38 + extra + length + 3) & ~3
    packed = zlib.compress(data, 9)
    constants = {"SIZE": len(data), "PARTITION": partition, "FSD": fsd,
                 "ROOT_ENTRY": root_entry, "ROOT_DIRECTORY": directory,
                 "FILE_ENTRY": entries["FILE.TXT"], "EMPTY_ENTRY": entries["EMPTY"],
                 "DIR_ENTRY": entries["DIR"]}
    text = "// Generated by tools/input/generate_udf_fixture.py; do not edit.\n"
    text += "// Copyright (C) 2026 The BoxedWine Team; SPDX-License-Identifier: GPL-2.0-or-later\n"
    for name, value in constants.items():
        text += f"constexpr U32 UDF_FIXTURE_{name} = {value};\n"
    text += "static const U8 udfFixtureCompressed[] = {\n"
    for start in range(0, len(packed), 20):
        text += "    " + ", ".join(f"0x{byte:02x}" for byte in packed[start:start + 20]) + ",\n"
    text += "};\n"
    target.write_text(text)
    print(f"Wrote {target}: {len(data)} bytes, {len(packed)} compressed; {constants}")


if __name__ == "__main__":
    main()
